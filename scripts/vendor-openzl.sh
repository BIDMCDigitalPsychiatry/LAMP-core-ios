#!/usr/bin/env bash
# Regenerates the vendored, pruned OpenZL source tree used by mindLAMP.
#
# Usage: vendor-openzl.sh <destination-dir> [openzl-tag]
#
# The destination receives:
#   openzl/            OpenZL C sources and public headers (no tools, tests, C++)
#   zstd/              zstd lib/{common,compress,decompress} + public headers
#   lz4/               lz4.c, lz4.h, lz4hc.c, lz4hc.h
#   config/openzl/zl_config.h   replaces the header OpenZL's CMake generates
#   LICENSES/          upstream licence files
#   VERSION            upstream tag and commits
#
# Compile every .c under openzl/src and zstd/, plus lz4/lz4.c and lz4/lz4hc.c,
# with one flag set (verified to give byte-identical frames to upstream CMake):
#   -std=gnu11 -D_GNU_SOURCE -D_REENTRANT -DZSTD_DISABLE_ASM=1
#   -DZSTD_LEGACY_SUPPORT=0 -DXXH_NAMESPACE=ZSTD_
# and include paths: config, openzl, openzl/include, openzl/src, zstd, lz4.

set -euo pipefail

DEST="${1:?usage: vendor-openzl.sh <destination-dir> [openzl-tag]}"
TAG="${2:-v0.3.0}"
WORK="$(mktemp -d)"
trap 'rm -rf "$WORK"' EXIT

git clone --quiet --depth 1 --branch "$TAG" https://github.com/facebook/openzl.git "$WORK/openzl"
git -C "$WORK/openzl" -c advice.detachedHead=false submodule update --init --depth 1 deps/zstd deps/lz4

rm -rf "$DEST"
mkdir -p "$DEST"/{openzl,zstd,lz4,config/openzl,LICENSES}

# OpenZL: C sources and headers only. The x86-64 assembly is excluded; the
# config below disables it (ZL_HAVE_X86_64_ASM 0), so the C fallback is used.
(cd "$WORK/openzl" && find src include -type f \( -name '*.c' -o -name '*.h' \) -print0 |
  xargs -0 -I{} rsync -R {} "$DEST/openzl/")

# zstd: the three library parts OpenZL links against, plus public headers.
(cd "$WORK/openzl/deps/zstd/lib" && find common compress decompress -type f \( -name '*.c' -o -name '*.h' \) -print0 |
  xargs -0 -I{} rsync -R {} "$DEST/zstd/")
cp "$WORK/openzl/deps/zstd/lib/"{zstd.h,zstd_errors.h,zdict.h} "$DEST/zstd/"

# lz4: block and HC compressors (lz4hc.c includes lz4.c's definitions).
cp "$WORK/openzl/deps/lz4/lib/"{lz4.c,lz4.h,lz4hc.c,lz4hc.h} "$DEST/lz4/"

cp "$WORK/openzl/LICENSE" "$DEST/LICENSES/openzl-LICENSE"
cp "$WORK/openzl/deps/zstd/LICENSE" "$DEST/LICENSES/zstd-LICENSE"
cp "$WORK/openzl/deps/lz4/lib/LICENSE" "$DEST/LICENSES/lz4-LICENSE"

cat > "$DEST/config/openzl/zl_config.h" <<'EOF'
// Hand-written replacement for the zl_config.h that OpenZL's CMake generates
// from build-scripts/cmake/zl_config.h.cmake. Values match the upstream
// defaults except x86-64 assembly, which is disabled for portability.

#ifndef OPENZL_ZS2_CONFIG_H
#define OPENZL_ZS2_CONFIG_H

#ifndef OPENZL_HAVE_X86_64_ASM
#define OPENZL_HAVE_X86_64_ASM ZL_HAVE_X86_64_ASM
#endif

#define ZL_ALLOW_INTROSPECTION 1

#define ZL_HAVE_X86_64_ASM 0

#endif
EOF

{
  echo "openzl $TAG $(git -C "$WORK/openzl" rev-parse HEAD)"
  echo "zstd $(git -C "$WORK/openzl/deps/zstd" rev-parse HEAD)"
  echo "lz4 $(git -C "$WORK/openzl/deps/lz4" rev-parse HEAD)"
  echo "generated by vendor-openzl.sh"
} > "$DEST/VERSION"

echo "Vendored OpenZL $TAG into $DEST ($(find "$DEST" -name '*.c' | wc -l | tr -d ' ') C files)"
